#include "launchx_common.h"

#define XKB_OPT_COUNT 216      /* total XKB options across all 22 groups */

struct options_xkb {
    int layout_sel[3];       /* per-row: 0 = Auto-detect, else index into layout_codes[] */
    char xkbmodel[128];
    char xkbvariant[3][64];  /* per-row variant code ("" = none), positional with layout_sel */
    int opt_sel[XKB_OPT_COUNT]; /* selected XKB options: 1 per flat option index */
    char xkboptions[2048];   /* derived -xkboptions string (persisted) */
    char xkbrules[128];
    char xkbdir[256];
};

/* Build the comma-joined -xkboptions value from opt_sel[], or parse a
   persisted/command-line value back into opt_sel[]. */
void xkb_options_build(char *out, size_t outsz, const struct options_xkb *opt);
void xkb_options_parse(struct options_xkb *opt, const char *str);

